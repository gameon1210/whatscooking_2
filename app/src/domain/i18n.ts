/** "rajma (soak overnight)" / "rice + moong dal" -> the cook's language. */
export function itemName(item: string, lang: CookLanguage): string {
  if (lang === 'en') return item;
  const i = IDX[lang];
  const soak = /\(soak overnight\)/.test(item);
  const base = item.replace(/\(.*?\)/g, '').trim();
  const parts = base.split('+').map((p) => p.trim()).map((p) => ITEM[p]?.[i] ?? p);
  return parts.join(' + ') + (soak ? ` (${SOAK[i]})` : '');
}

